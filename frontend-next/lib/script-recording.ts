/**
 * Ported from the legacy js/analyzer.js, js/generator.js, and js/metadata.js.
 * Field metadata table and code-generation rules are kept in lockstep with
 * the original SAP GUI recording parser so generated scripts stay consistent.
 */

export type RecordedAction = {
  seq: number;
  action: "SET_TEXT" | "SEND_VKEY" | "PRESS";
  field?: string;
  locator?: string;
  sample_value?: string;
};

export type RecordedField = {
  field: string;
  locator?: string;
  sample_value?: string;
};

export type AnalyzeResult = {
  success: boolean;
  transaction: string;
  action_count: number;
  field_count: number;
  errors: string[];
  fields: RecordedField[];
  actions: RecordedAction[];
  message?: string;
};

export type FieldMetadata = {
  variable: string;
  description: string;
  classification: string;
  generator: string;
  required: boolean;
};

